"""Turn scanner output into [functions] entries: pick_missed.py <bin> <scan_data.txt> <scan_code.txt>

Rules (from Skate 1, tightened):
- data-pointer hits marked START whose first instruction has a real primary opcode;
- code-pointer (lis/addi) hits whose first instruction reads/writes no r14-r31 register
  (a function start can't rely on callee-saved registers holding its own values);
- never an address inside an existing .pdata function (that would split a real function).
Prints TOML to stdout and the rejected candidates to stderr.
"""
import re
import struct
import sys

BASE = 0x82000000
PDATA, PDATA_COUNT = 0x820EAA00, 14375
data = open(sys.argv[1], 'rb').read()
ranges = []
for i in range(PDATA_COUNT):
    b, info = struct.unpack_from('>II', data, PDATA - BASE + i * 8)
    ranges.append((b, b + ((info >> 8) & 0x3FFFFF) * 4))


def inside_pdata(a):
    return any(lo < a < hi for lo, hi in ranges)


# Primary opcodes that are not valid instructions on Xenon (0 = padding/data, 1/5/6 unused).
BAD_OPS = {0, 1, 2, 5, 6, 9, 22, 56, 57, 60, 61}


def uses_saved_reg(x):
    op = x >> 26
    regs = [(x >> 21) & 31, (x >> 16) & 31]
    if op == 31:
        regs.append((x >> 11) & 31)
    return any(14 <= r <= 31 for r in regs)


picked, rejected = {}, []
for line in open(sys.argv[2]):
    m = re.match(r'([0-9A-F]{8}) .*first_ref=([0-9A-F]{8}) first_ins=([0-9A-F]{8}) (\w+)', line)
    if not m:
        continue
    a, ref, ins, kind = int(m[1], 16), m[2], int(m[3], 16), m[4]
    why = None
    if kind != 'START':
        why = 'interior'
    elif ins >> 26 in BAD_OPS:
        why = f'opcode {ins >> 26}'
    elif inside_pdata(a):
        why = 'inside .pdata function'
    if why:
        rejected.append(f'{a:08X} data {why}')
    else:
        picked[a] = f'data ptr at 0x{ref}'

for line in open(sys.argv[3]):
    m = re.match(r'([0-9A-F]{8}) ref=([0-9A-F]{8}) first_ins=([0-9A-F]{8})', line)
    if not m:
        continue
    a, ref, ins = int(m[1], 16), m[2], int(m[3], 16)
    why = None
    if ins >> 26 in BAD_OPS:
        why = f'opcode {ins >> 26}'
    elif uses_saved_reg(ins):
        why = 'touches r14-r31'
    elif inside_pdata(a):
        why = 'inside .pdata function'
    if why:
        rejected.append(f'{a:08X} code {why}')
    else:
        picked.setdefault(a, f'lis/addi at 0x{ref}')

print('# Generated by tools/pick_missed.py from tools/scan_data_ptrs.py and tools/scan_code_ptrs.py.')
print('# Function starts with no .pdata entry, reached only through pointers (static initializers,')
print('# vtables, callbacks). Re-generate after each codegen; hand fixes go in fifastreet3_functions.toml.')
print('[functions]')
for a in sorted(picked):
    print(f'0x{a:08X} = {{}}  # {picked[a]}')
for r in rejected:
    print(r, file=sys.stderr)
print(f'picked {len(picked)}, rejected {len(rejected)}', file=sys.stderr)
